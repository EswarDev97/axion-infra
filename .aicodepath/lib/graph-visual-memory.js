#!/usr/bin/env node
/**
 * Graph Visual Memory — register code graph HTML output in the visual memory index.
 *
 * Called from JS (hook or MCP wrapper) after graph_visualizer.py produces an
 * interactive HTML file.  Stores the registration in the `visual_diagrams` DB
 * table using `diagram_type = "graph-interactive"` so that
 *   node visual-memory-writer.js list | grep "graph-interactive"
 * returns at least one hit.
 *
 * @module lib/graph-visual-memory
 */

'use strict';

const path = require('path');
const fs   = require('fs');
const { findProjectRoot, getDbPath } = require('./path-resolver');
const logger = require('./logger');

/**
 * Default output path produced by graph_visualizer.py.
 * Relative to project root.
 */
const DEFAULT_HTML_REL = path.join('aicodepath-docs', 'memory', 'global', 'code-graph.html');

/**
 * Register (or refresh) a code-graph HTML visualisation in the visual memory DB.
 *
 * Uses `diagram_type = "graph-interactive"` so downstream tooling can grep for
 * that exact string.  The mermaidContent field stores the absolute HTML path as
 * a short stub — the DB table requires a non-empty string, but the real content
 * is the HTML file on disk.
 *
 * @param {string} [htmlPath] - Absolute path to the HTML file produced by the
 *   graph visualiser.  Defaults to `<projectRoot>/aicodepath-docs/memory/global/code-graph.html`.
 * @returns {{ id: number, filePath: string, name: string, diagramType: string }}
 */
function registerCodeGraph(htmlPath) {
  const projectRoot = findProjectRoot(process.cwd());
  const resolvedHtmlPath = htmlPath
    ? (path.isAbsolute(htmlPath) ? htmlPath : path.join(projectRoot, htmlPath))
    : path.join(projectRoot, DEFAULT_HTML_REL);

  // Lazy-require VisualMemoryWriter — it opens the DB; fail gracefully if DB not ready.
  const VisualMemoryWriter = require('./visual-memory-writer');
  const writer = new VisualMemoryWriter(projectRoot);

  try {
    // Ensure directory structure exists
    writer.initializeMemoryFolder();

    // Stub content — the actual visualisation lives in the HTML file on disk.
    const stubContent = `graph-interactive: ${resolvedHtmlPath}`;

    const result = writer.storeDiagram({
      diagramType:      'graph-interactive',
      name:             'code-graph',
      scope:            'global',
      title:            'Code Graph — Interactive HTML Visualisation',
      description:      `Interactive dependency graph generated by graph_visualizer.py. HTML output: ${resolvedHtmlPath}`,
      mermaidContent:   stubContent,
      generationMethod: 'static-ast',
      confidence:       0.9,
      sourceFiles:      [],
      syncStrategy:     'lazy',
      priority:         70,
      relevanceTags:    ['graph-interactive', 'code-graph', 'ast', 'dependencies'],
      crNumber:         'CR-CODE-GRAPH',
    });

    logger.info('graph-visual-memory: registered code graph HTML', {
      context:  'graph-visual-memory',
      id:       result.id,
      htmlPath: resolvedHtmlPath,
    });

    return result;
  } finally {
    writer.close();
  }
}

module.exports = { registerCodeGraph, DEFAULT_HTML_REL };

// ── CLI ──────────────────────────────────────────────────────────────────────
if (require.main === module) {
  const [,, command, arg] = process.argv;

  switch (command) {
    case 'register': {
      try {
        const result = registerCodeGraph(arg || undefined);
        console.log(`registered: diagram_type=graph-interactive  id=${result.id}  file=${result.filePath}`);
      } catch (err) {
        console.error(`registration failed: ${err.message}`);
        process.exit(1);
      }
      break;
    }

    default:
      console.log(`
Graph Visual Memory — register / inspect code-graph HTML in AICodePath visual memory

Usage:
  node graph-visual-memory.js register [<html-path>]
      Register the code-graph HTML (default: aicodepath-docs/memory/global/code-graph.html).

  node visual-memory-writer.js list
      List all registered diagrams (includes "graph-interactive" entries).
`);
  }
}
