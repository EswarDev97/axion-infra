/**
 * Get path to .env.aicodepath file
 *
 * @param {string} targetProjectRoot - Absolute path to target project root
 * @returns {string} - Path to .env.aicodepath file
 */
function getEnvFilePath(targetProjectRoot) {
  return path.join(targetProjectRoot, '.env.aicodepath');
}

/**
 * Check if .env.aicodepath already exists
 *
 * @param {string} targetProjectRoot - Absolute path to target project root
 * @returns {boolean} - True if file exists
 */
function envFileExists(targetProjectRoot) {
  const envPath = getEnvFilePath(targetProjectRoot);
  return fs.existsSync(envPath);
}

/**
 * Generate .env.aicodepath for target project
 *
 * Creates a .env.aicodepath file with documented environment variables.
 * If file already exists, it is not overwritten (preserves user changes).
 *
 * @param {string} targetProjectRoot - Absolute path to target project root
 * @param {Object} options - Generation options
 * @param {boolean} options.overwrite - Force overwrite if file exists (default: false)
 * @param {boolean} options.addTimestamp - Add generation timestamp (default: true)
 * @returns {Object} - Result { success, envPath, created, skipped, error }
 */
function generateEnvConfig(targetProjectRoot, options = {}) {
  const { overwrite = false, addTimestamp = true } = options;

  if (!targetProjectRoot || !path.isAbsolute(targetProjectRoot)) {
    throw new Error('Target project root must be an absolute path');
  }

  const endTimer = logger.startTimer('env-config-generation');
  const envPath = getEnvFilePath(targetProjectRoot);

  const result = {
    success: false,
    envPath,
    created: false,
    skipped: false,
    error: null
  };

  try {
    // Check if file exists
    if (envFileExists(targetProjectRoot) && !overwrite) {
      logger.info('.env.aicodepath already exists, skipping creation', { envPath });
      result.success = true;
      result.skipped = true;
      endTimer({ success: true, skipped: true });
      return result;
    }

    // Get template content
    let content = getDefaultEnvTemplate();

    // Add timestamp if requested
    if (addTimestamp) {
      const now = new Date().toISOString();
      content = content.replace('$(date)', now);
    }

    // Write .env.aicodepath file
    fs.writeFileSync(envPath, content, 'utf8');

    result.success = true;
    result.created = true;

    logger.info('Generated .env.aicodepath', { envPath });

    endTimer({ success: true, created: true });

  } catch (error) {
    result.error = error.message;
    logger.error('Failed to generate .env.aicodepath', {
      envPath,
      error: error.message,
      stack: process.env.DEBUG ? error.stack : undefined
    });
    endTimer({ success: false, error: error.message });
  }

  return result;
}

/**
 * Parse .env.aicodepath and return as key-value object
 *
 * @param {string} targetProjectRoot - Absolute path to target project root
 * @returns {Object} - Parsed environment variables
 */
function parseEnvConfig(targetProjectRoot) {
  const envPath = getEnvFilePath(targetProjectRoot);

  if (!fs.existsSync(envPath)) {
    return {};
  }

  try {
    const content = fs.readFileSync(envPath, 'utf8');
    const envVars = {};

    for (const line of content.split('\n')) {
      const trimmed = line.trim();

      // Skip comments and empty lines
      if (!trimmed || trimmed.startsWith('#')) {
        continue;
      }

      // Parse KEY=VALUE
      const eqIndex = trimmed.indexOf('=');
      if (eqIndex > 0) {
        const key = trimmed.substring(0, eqIndex).trim();
        const value = trimmed.substring(eqIndex + 1).trim();
        envVars[key] = value;
      }
    }

    return envVars;
  } catch (error) {
    logger.error('Failed to parse .env.aicodepath', {
      envPath,
      error: error.message
    });
    return {};
  }
}

/**
 * Check if development mode is enabled via environment config
 *
 * @param {string} targetProjectRoot - Absolute path to target project root
 * @returns {boolean} - True if dev mode is enabled
 */
function isDevModeEnabled(targetProjectRoot) {
  // Check environment variable first
  if (process.env.AICODEPATH_DEV_MODE === 'true') {
    return true;
  }
  if (process.env.AICODEPATH_HOOK_DEV === 'true') {
    return true;
  }

  // Check .env.aicodepath file
  const envVars = parseEnvConfig(targetProjectRoot);
  if (envVars.AICODEPATH_DEV_MODE === 'true') {
    return true;
  }
  if (envVars.AICODEPATH_HOOK_DEV === 'true') {
    return true;
  }

  // Check auto-detection (project path contains 'aicodepath-tool')
  return targetProjectRoot.includes('aicodepath-tool');
}

module.exports = {
  generateEnvConfig,
  getDefaultEnvTemplate,
  getEnvFilePath,
  envFileExists,
  parseEnvConfig,
  isDevModeEnabled
};
